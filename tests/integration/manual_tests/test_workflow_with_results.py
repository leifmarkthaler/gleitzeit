#!/usr/bin/env python
"""Test workflow submission with centralized ID management and monitor results."""

import asyncio
import aiohttp
import json
import time

async def submit_and_monitor_workflow():
    """Submit workflow and monitor its execution."""
    
    # Simple workflow that will produce results
    workflow_data = {
        "name": "test-workflow-with-results",
        "tasks": [
            {
                "name": "hello_task",
                "protocol": "python",
                "method": "script",
                "params": {
                    "script": "examples/scripts/hello.py"
                }
            },
            {
                "name": "math_task",
                "protocol": "python", 
                "method": "script",
                "params": {
                    "script": "examples/scripts/math_ops.py",
                    "args": ["25", "17"]
                },
                "dependencies": ["hello_task"]
            }
        ]
    }
    
    async with aiohttp.ClientSession() as session:
        # Submit workflow
        url = "http://localhost:8100/api/v1/workflows"
        print("=" * 60)
        print("SUBMITTING WORKFLOW WITH CENTRALIZED ID MANAGEMENT")
        print("=" * 60)
        print(f"\nWorkflow definition:\n{json.dumps(workflow_data, indent=2)}")
        
        try:
            async with session.post(url, json={"workflow": workflow_data}) as response:
                if response.status == 200:
                    result = await response.json()
                    workflow_id = result.get('workflow_id')
                    print(f"\n✅ Workflow submitted successfully!")
                    print(f"   Workflow ID (generated by WorkflowLoaderV2): {workflow_id}")
                    print(f"   Status: {result.get('status')}")
                    
                    # Monitor workflow execution
                    print("\n" + "=" * 60)
                    print("MONITORING WORKFLOW EXECUTION")
                    print("=" * 60)
                    
                    for i in range(10):  # Check for up to 10 seconds
                        await asyncio.sleep(1)
                        
                        # Get workflow status
                        status_url = f"http://localhost:8100/api/v1/workflows/{workflow_id}"
                        async with session.get(status_url) as status_response:
                            if status_response.status == 200:
                                workflow_status = await status_response.json()
                                status = workflow_status.get('status')
                                print(f"\n[{i+1}s] Workflow status: {status}")
                                
                                # Check if all tasks have workflow_id set
                                tasks = workflow_status.get('tasks', [])
                                if tasks:
                                    print(f"   Tasks: {len(tasks)}")
                                    for task in tasks:
                                        task_id = task.get('id')
                                        task_wf_id = task.get('workflow_id')
                                        task_status = task.get('status')
                                        print(f"     - {task.get('name')} ({task_id}): status={task_status}, workflow_id={task_wf_id}")
                                
                                # If completed, get results
                                if status == 'completed':
                                    print("\n" + "=" * 60)
                                    print("WORKFLOW COMPLETED - FETCHING RESULTS")
                                    print("=" * 60)
                                    
                                    # Get task results
                                    results_url = f"http://localhost:8100/api/v1/workflows/{workflow_id}/results"
                                    async with session.get(results_url) as results_response:
                                        if results_response.status == 200:
                                            results = await results_response.json()
                                            print(f"\nTask Results:")
                                            for task_result in results:
                                                print(f"\n  Task: {task_result.get('task_id')}")
                                                print(f"  Status: {task_result.get('status')}")
                                                if task_result.get('result'):
                                                    print(f"  Output: {task_result.get('result')}")
                                    
                                    print("\n" + "=" * 60)
                                    print("✅ CENTRALIZED WORKFLOW ID MANAGEMENT WORKING!")
                                    print("=" * 60)
                                    print("\nKey points demonstrated:")
                                    print("1. Workflow ID generated centrally by WorkflowLoaderV2")
                                    print("2. All tasks have workflow_id properly set")
                                    print("3. Workflow executed successfully with results")
                                    return
                                
                                elif status == 'failed':
                                    print("\n❌ Workflow failed!")
                                    return
                    
                    print("\n⏱️  Workflow still running after 10 seconds...")
                    
                else:
                    error = await response.text()
                    print(f"\n❌ Failed to submit workflow!")
                    print(f"   Status: {response.status}")
                    print(f"   Error: {error}")
                    
        except Exception as e:
            print(f"\n❌ Error: {e}")

if __name__ == "__main__":
    asyncio.run(submit_and_monitor_workflow())