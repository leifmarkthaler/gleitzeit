def generate_jwt_secret() -> str:
    """Generate a secure JWT secret"""
    return secrets.token_urlsafe(32)


def save_auth_config(config: Dict[str, Any]) -> Path:
    """Save authentication configuration to file"""
    config_dir = Path.home() / ".gleitzeit"
    config_dir.mkdir(parents=True, exist_ok=True)
    
    config_file = config_dir / "config.yaml"
    
    # Load existing config if it exists
    existing_config = {}
    if config_file.exists():
        with open(config_file, 'r') as f:
            existing_config = yaml.safe_load(f) or {}
    
    # Merge with new auth config
    existing_config['auth'] = config
    
    # Save merged config
    with open(config_file, 'w') as f:
        yaml.dump(existing_config, f, default_flow_style=False)
    
    return config_file


def save_env_file(env_vars: Dict[str, str]) -> Path:
    """Save environment variables to .env file"""
    config_dir = Path.home() / ".gleitzeit"
    config_dir.mkdir(parents=True, exist_ok=True)
    
    env_file = config_dir / ".env"
    
    # Read existing env vars if file exists
    existing_vars = {}
    if env_file.exists():
        with open(env_file, 'r') as f:
            for line in f:
                line = line.strip()
                if line and not line.startswith('#') and '=' in line:
                    key, value = line.split('=', 1)
                    existing_vars[key] = value
    
    # Update with new vars
    existing_vars.update(env_vars)
    
    # Write back
    with open(env_file, 'w') as f:
        f.write("# Gleitzeit Authentication Configuration\n")
        f.write("# Generated by gleitzeit auth setup\n\n")
        
        for key, value in sorted(existing_vars.items()):
            f.write(f"{key}={value}\n")
    
    return env_file


